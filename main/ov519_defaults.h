// Full power-on register images for the OV519 bridge and OV7648 sensor. The base
// image is PCSX2's hardware-proven EyeToy emulation (pcsx2/USB/usb-eyetoy:
// ov519_defaults / ov7648_defaults, SPDX GPL-3.0+), which drives the SAME OV519
// bridge + OV7648 sensor silicon. The official Xbox Video Chat minidriver reads
// back several bridge regs during bring-up (notably 0x00 = chip id 0xC0 and
// 0x53 = 0xFF), so a sparse "IDs only" file makes it reject the device -- ship
// the whole image.
//
// BUT PCSX2 emulates the PlayStation EyeToy (054C:0155), not the Xbox Video
// Camera (045E:028C), so a few bytes carried PlayStation-board-specific values.
// These documented registers are aligned to the OV519 datasheet chip defaults
// (info/OV519.pdf register table) so the image is Xbox-appropriate:
//   0x57 SNAPSHOT   21 -> 01   (datasheet default; app overwrites at init)
//   0x70 GPIO_IN0   b4 -> 84   (clear GPIO[5:4] audio bits: Xbox has audio
//                               DISABLED via GPIO 4/5 -- the cam is video-only,
//                               no mic; PCSX2's 0xb4 said 24kHz-audio-enabled)
//   0x8c IO_N       7f -> 1f   (datasheet; [4:0] field value is unchanged)
//   0xb4 AVG_VEA    2d -> 3d   (datasheet; averaging window, not the video path)
// 0x53 is kept at 0xFF (the value the Xbox app reads back and requires, per the
// live UART trace -- NOT the datasheet power-on 0x87). Undocumented/factory-
// reserved regs the app uses (0x00, 0x37, 0x40-0x47 SCCB, 0xa2-0xa5) keep their
// PCSX2/HW-validated values -- the datasheet marks those "Do Not Access".
